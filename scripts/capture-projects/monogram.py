"""Write public/favicon.svg: the "OB" monogram as outlined Space Grotesk Bold.

Outlines, not <text>: a favicon's text renders in whatever font the OS has,
so the monogram looked different everywhere. This reads the site's own
Space Grotesk (src/assets/fonts), pins the variable font at weight 700 and
converts O and B to SVG paths.

    python monogram.py      (needs fonttools + brotli)

identity.mjs rasterises the result into the PNG/ICO sizes.
"""
import io
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / 'src/assets/fonts/space-grotesk-latin.woff2'
OUT = ROOT / 'public/favicon.svg'

BOX = 64          # viewBox size
CAP = 30          # cap height of the letters in viewBox units (legible at 16px)
GAP = 1.5         # space between O and B, viewBox units
BG = '#0E6A63'    # light-theme accent (contrast with white: 6.4:1)
FG = '#FFFFFF'

font = TTFont(io.BytesIO(FONT.read_bytes()))
font = instantiateVariableFont(font, {'wght': 700})
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
cap_height = font['OS/2'].sCapHeight
scale = CAP / cap_height


def bounds(name):
    from fontTools.pens.boundsPen import BoundsPen
    pen = BoundsPen(glyphs)
    glyphs[name].draw(pen)
    return pen.bounds  # xMin, yMin, xMax, yMax


letters = [cmap[ord(c)] for c in 'OB']
boxes = [bounds(n) for n in letters]
widths = [(b[2] - b[0]) * scale for b in boxes]
total = sum(widths) + GAP
x = (BOX - total) / 2
baseline = (BOX + CAP) / 2

paths = []
for name, box, width in zip(letters, boxes, widths):
    pen = SVGPathPen(glyphs, ntos=lambda v: f'{v:.2f}'.rstrip('0').rstrip('.'))
    # Font units are y-up; SVG is y-down. Shift each glyph so its ink starts at x.
    glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x - box[0] * scale, baseline)))
    paths.append(pen.getCommands())
    x += width + GAP

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {BOX} {BOX}" role="img" aria-label="OB">
  <!-- Generated by scripts/capture-projects/monogram.py (Space Grotesk Bold, outlined). -->
  <rect width="{BOX}" height="{BOX}" rx="14" fill="{BG}" />
  <path fill="{FG}" d="{' '.join(paths)}" />
</svg>
'''
OUT.write_text(svg, encoding='utf-8', newline='\n')
print(f'wrote {OUT} ({len(svg)} bytes)', file=sys.stderr)
